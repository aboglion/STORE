#!/usr/bin/env bash
#
# Generates .env.local from the running local Supabase stack.
#
# Usage:
#   bash scripts/env-local.sh
#
# Reads the keys printed by `supabase status -o env` and maps them to the
# variable names the app expects (see .env.example).
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

STATUS_ENV="$(npx supabase status -o env 2>/dev/null || true)"

API_URL="$(printf '%s\n' "${STATUS_ENV}" | sed -n 's/^API_URL="\(.*\)"/\1/p')"
ANON_KEY="$(printf '%s\n' "${STATUS_ENV}" | sed -n 's/^ANON_KEY="\(.*\)"/\1/p')"
SERVICE_ROLE_KEY="$(printf '%s\n' "${STATUS_ENV}" | sed -n 's/^SERVICE_ROLE_KEY="\(.*\)"/\1/p')"

if [ -z "${API_URL}" ] || [ -z "${ANON_KEY}" ] || [ -z "${SERVICE_ROLE_KEY}" ]; then
  echo "❌ Supabase stack is not running. Start it first: make db-start" >&2
  exit 1
fi

# שמירת ערכים קיימים מ-.env.local או .env (כגון דומיין אמיתי או סיסמת אדמין)
EXISTING_SITE_URL=""
EXISTING_ADMIN_EMAIL=""
EXISTING_ADMIN_PASSWORD=""
if [ -f .env.local ]; then
  EXISTING_SITE_URL="$(grep -E '^NEXT_PUBLIC_SITE_URL=' .env.local | head -1 | cut -d= -f2- || true)"
  EXISTING_ADMIN_EMAIL="$(grep -E '^ADMIN_EMAIL=' .env.local | head -1 | cut -d= -f2- || true)"
  EXISTING_ADMIN_PASSWORD="$(grep -E '^ADMIN_PASSWORD=' .env.local | head -1 | cut -d= -f2- || true)"
elif [ -f .env ]; then
  EXISTING_SITE_URL="$(grep -E '^NEXT_PUBLIC_SITE_URL=' .env | head -1 | cut -d= -f2- || true)"
  EXISTING_ADMIN_EMAIL="$(grep -E '^ADMIN_EMAIL=' .env | head -1 | cut -d= -f2- || true)"
  EXISTING_ADMIN_PASSWORD="$(grep -E '^ADMIN_PASSWORD=' .env | head -1 | cut -d= -f2- || true)"
fi

SITE_URL="${NEXT_PUBLIC_SITE_URL:-${EXISTING_SITE_URL:-http://localhost}}"
if [ "$SITE_URL" = "http://localhost:3000" ] || [ "$SITE_URL" = "http://127.0.0.1:3000" ]; then
  SITE_URL="http://localhost"
fi

cat > .env.local <<EOF
# Auto-generated by scripts/env-local.sh
# Regenerate with: make env
NEXT_PUBLIC_SUPABASE_URL=${API_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}
NEXT_PUBLIC_SITE_URL=${SITE_URL}
TZ=Asia/Jerusalem
EOF

if [ -n "${EXISTING_ADMIN_EMAIL}" ]; then
  echo "ADMIN_EMAIL=${EXISTING_ADMIN_EMAIL}" >> .env.local
fi
if [ -n "${EXISTING_ADMIN_PASSWORD}" ]; then
  echo "ADMIN_PASSWORD=${EXISTING_ADMIN_PASSWORD}" >> .env.local
fi

cp -f .env.local .env

echo "✅ .env.local and .env written (${API_URL})"