/**
 * Searches the Israeli cities and villages list.
 * Matches Hebrew names, Arabic names, aliases, and substring queries.
 */
export function searchIsraelCities(query: string, limit = 15): IsraelCity[] {
    const q = (query || "").trim().toLowerCase();
    if (!q) return ISRAEL_CITIES.slice(0, limit);

    // Normalize Arabic/Hebrew letters (remove diacritics/variations if any)
    const norm = (str: string) =>
        str
            .toLowerCase()
            .replace(/[-"']/g, "")
            .replace(/[أإآ]/g, "ا")
            .replace(/ة/g, "ه")
            .replace(/ى/g, "ي")
            .replace(/\s+/g, " ");

    const nq = norm(q);

    const matches: { city: IsraelCity; score: number }[] = [];

    for (const city of ISRAEL_CITIES) {
        const he = norm(city.nameHe);
        const ar = norm(city.nameAr);
        const aliases = (city.aliases || []).map(norm);

        let score = -1;
        if (he === nq || ar === nq || aliases.includes(nq)) {
            score = 100;
        } else if (he.startsWith(nq) || ar.startsWith(nq)) {
            score = 80;
        } else if (aliases.some((a) => a.startsWith(nq))) {
            score = 70;
        } else if (he.includes(nq) || ar.includes(nq)) {
            score = 50;
        } else if (aliases.some((a) => a.includes(nq))) {
            score = 40;
        }

        if (score > 0) {
            matches.push({ city, score });
        }
    }

    matches.sort((a, b) => b.score - a.score);
    return matches.slice(0, limit).map((m) => m.city);
}

/**
 * Exact or best match for a given city string.
 */
export function findIsraelCity(name: string): IsraelCity | null {
    if (!name || !name.trim()) return null;
    const results = searchIsraelCities(name, 1);
    return results[0] ?? null;
}
