import { Suspense } from "react";
import type { Metadata, Viewport } from "next";
import localFont from "next/font/local";
import { NextIntlClientProvider } from "next-intl";
import { getLocale, getMessages } from "next-intl/server";

import { AccessibilityWidget } from "@/components/accessibility/accessibility-widget";
import { PwaRegister } from "@/components/pwa/pwa-register";
import { NavigationProgress } from "@/components/ui/navigation-progress";
import { Toaster } from "@/components/ui/sonner";
import { getPublicSettings } from "@/lib/data/storefront";
import { DEFAULT_STORE_THEME } from "@/lib/theme";

import "./globals.css";

const notoSansHebrew = localFont({
    src: "../public/fonts/noto-sans-hebrew.woff2",
    variable: "--font-hebrew",
});

const frankRuhlLibre = localFont({
    src: "../public/fonts/frank-ruhl-libre-hebrew.woff2",
    weight: "400 900",
    style: "normal",
    variable: "--font-display-hebrew",
});

const notoSansArabic = localFont({
    src: "../public/fonts/noto-sans-arabic.woff2",
    variable: "--font-arabic",
});

const cairo = localFont({
    src: "../public/fonts/cairo-arabic.woff2",
    weight: "400 900",
    variable: "--font-display-arabic",
});

export async function generateMetadata(): Promise<Metadata> {
    const locale = await getLocale();
    const isAr = locale === "ar";

    let storeName = isAr ? "جولدن ماركت" : "גולדן מארקט";
    try {
        const settings = await getPublicSettings();
        storeName = isAr
            ? settings.store_name_ar || settings.store_name || storeName
            : settings.store_name || storeName;
    } catch {
        // Keep the default name when settings are unavailable.
    }

    return {
        title: {
            default: storeName,
            template: `%s | ${storeName}`,
        },
        description: isAr
            ? "سوبر ماركت جولدن ماركت رهط — طلب سهل وتوصيل حتى البيت"
            : "סופרמרקט גולדן מארקט רהט — הזמנה קלה ומשלוח עד הבית",
        // The manifest is generated by app/manifest.ts and auto-linked by
        // Next.js at /manifest.webmanifest — no need for an explicit pointer.
        appleWebApp: {
            capable: true,
            statusBarStyle: "default",
            title: storeName,
        },
        icons: {
            icon: [
                { url: "/icon.svg", type: "image/svg+xml" },
                { url: "/icon-192.png", sizes: "192x192", type: "image/png" },
                { url: "/icon-512.png", sizes: "512x512", type: "image/png" },
            ],
            apple: [
                { url: "/apple-touch-icon.png", sizes: "180x180", type: "image/png" },
            ],
        },
    };
}

export const viewport: Viewport = {
    width: "device-width",
    initialScale: 1,
    viewportFit: "cover",
    themeColor: "#95582b",
};

export default async function RootLayout({
    children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    const locale = await getLocale();
    const messages = await getMessages();

    let theme = DEFAULT_STORE_THEME;
    try {
        const settings = await getPublicSettings();
        theme = settings.theme;
    } catch {
        theme = DEFAULT_STORE_THEME;
    }

    return (
        <html
            lang={locale}
            dir="rtl"
            data-theme={theme}
            className={`${notoSansHebrew.variable} ${frankRuhlLibre.variable} ${notoSansArabic.variable} ${cairo.variable}`}
        >
            <body className="min-h-screen font-sans antialiased">
                <NextIntlClientProvider locale={locale} messages={messages} timeZone="Asia/Jerusalem">
                    <PwaRegister />
                    <Suspense fallback={null}>
                        <NavigationProgress />
                    </Suspense>
                    <AccessibilityWidget />
                    {children}
                    <Toaster />
                </NextIntlClientProvider>
            </body>
        </html>
    );
}
